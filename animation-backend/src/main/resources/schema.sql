CREATE TABLE IF NOT EXISTS shared_stories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_username VARCHAR(30) NOT NULL,
    author_display_name VARCHAR(60) NOT NULL,
    title VARCHAR(120) NOT NULL,
    content CLOB NOT NULL,
    tags VARCHAR(200) NOT NULL DEFAULT '',
    historical_date VARCHAR(100) NOT NULL DEFAULT '',
    place_name VARCHAR(120) NOT NULL DEFAULT '',
    latitude DOUBLE,
    longitude DOUBLE,
    image_content_type VARCHAR(40),
    image_data BLOB,
    created_at VARCHAR(40) NOT NULL,
    updated_at VARCHAR(40) NOT NULL
);

